    /**
     * An icon as a data URI, in the colour asked for.
     *
     * Returns null for a label with no icon, so a caller that adds a row and
     * forgets to add an icon gets an empty tile rather than a broken image.
     */
    public static function dataUri(string $label, string $color = '#ffffff'): ?string
    {
        $key = self::FOR_LABEL[$label] ?? null;

        if ($key === null || ! isset(self::ICONS[$key])) {
            return null;
        }

        [$viewBox, $path] = self::ICONS[$key];

        return 'data:image/svg+xml;base64,'.base64_encode(
            '<svg xmlns="http://www.w3.org/2000/svg" viewBox="'.$viewBox.'">'
            .'<path fill="'.$color.'" d="'.$path.'"/></svg>'
        );
    }
